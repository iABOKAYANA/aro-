import { useCallback, useState } from 'react';

import * as ImagePicker from 'expo-image-picker';

import { API_URL } from '@/api/config';
import { useAuth } from '@/auth/auth-context';

/**
 * Phone twin of the website's `uploadImageFile` in
 * src/app/ceo/components/image-input.tsx.
 *
 * Contract (src/app/api/ceo/upload/route.ts, mirrored by
 * src/app/api/developer/upload/route.ts): `POST <endpoint>` with the
 * file in a multipart field literally named `file`, session attached the
 * same way as every other mobile request (`X-Session-Token`, see
 * src/api/client.ts). Success answers `{ url: '/images/uploads/<name>' }`.
 *
 * The fetch lives here instead of going through `apiFetch` on purpose:
 * `apiFetch` stamps `Content-Type: application/json` on every bodied request,
 * which corrupts a multipart upload (the boundary must be generated by
 * fetch). Only the token header is borrowed, not the JSON behaviour.
 */

/** Same 5MB ceiling the route enforces — checked first for a friendly error. */
export const UPLOAD_MAX_SIZE = 5 * 1024 * 1024;

/** Same allow-list the route enforces (`ALLOWED` in the route handler). */
export const ALLOWED_MIME_TYPES: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/gif': '.gif',
  'image/svg+xml': '.svg',
  'image/avif': '.avif',
};

const EXT_TO_MIME: Record<string, string> = {
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  gif: 'image/gif',
  svg: 'image/svg+xml',
  avif: 'image/avif',
};

export type UploadErrorCode = 'too-large' | 'bad-type' | 'failed';

/** Thrown with a stable code so screens map it to an i18n string — never raw. */
export class ImageUploadError extends Error {
  readonly code: UploadErrorCode;

  constructor(code: UploadErrorCode) {
    super(code);
    this.name = 'ImageUploadError';
    this.code = code;
  }
}

type PickedAsset = {
  uri: string;
  fileName?: string | null;
  mimeType?: string | null;
  fileSize?: number | null;
};

function extensionOf(fileName: string | null | undefined, uri: string): string | null {
  const source = fileName || uri.split('?')[0];
  const base = source.split('/').pop() ?? '';
  const dot = base.lastIndexOf('.');
  if (dot < 0) return null;
  return base.slice(dot + 1).toLowerCase() || null;
}

/**
 * Resolve the asset to an allow-listed MIME type.
 *
 * - A reported MIME wins outright: allowed passes, anything else (HEIC, BMP,
 *   video…) is rejected here instead of a server 400.
 * - With no reported MIME, fall back to the file extension when there is one.
 * - With neither signal, return `null` and let the server decide rather than
 *   blocking a valid photo (some Android providers report nothing).
 */
function mimeOf(asset: PickedAsset): string | null | undefined {
  if (asset.mimeType) {
    return ALLOWED_MIME_TYPES[asset.mimeType] ? asset.mimeType : undefined;
  }
  const ext = extensionOf(asset.fileName, asset.uri);
  if (!ext) return null;
  return EXT_TO_MIME[ext];
}

/**
 * Validate + POST one picked asset, resolving the stored path exactly as the
 * website fills its field with it (`/images/uploads/<name>`).
 *
 * `endpoint` selects the upload door — the default keeps every existing
 * caller on the CEO route byte-identical; developer screens pass
 * `/api/developer/upload`.
 */
export async function uploadImageAsset(
  asset: PickedAsset,
  token: string | null | undefined,
  endpoint: string = '/api/ceo/upload',
): Promise<string> {
  if (typeof asset.fileSize === 'number' && asset.fileSize > UPLOAD_MAX_SIZE) {
    throw new ImageUploadError('too-large');
  }

  const mime = mimeOf(asset);
  if (mime === undefined) {
    throw new ImageUploadError('bad-type');
  }

  const ext = mime
    ? ALLOWED_MIME_TYPES[mime]
    : (() => {
        const raw = extensionOf(asset.fileName, asset.uri);
        return raw ? `.${raw}` : '.jpg';
      })();
  const name = asset.fileName || `upload-${Date.now()}${ext}`;

  const body = new FormData();
  body.append('file', { uri: asset.uri, name, type: mime ?? 'image/jpeg' } as unknown as Blob);

  let response: Response;
  try {
    response = await fetch(`${API_URL}${endpoint}`, {
      method: 'POST',
      headers: {
        Accept: 'application/json',
        ...(token ? { 'X-Session-Token': encodeURIComponent(token) } : {}),
      },
      body,
    });
  } catch {
    throw new ImageUploadError('failed');
  }

  const data = (await response.json().catch(() => null)) as { url?: unknown } | null;
  if (!response.ok || typeof data?.url !== 'string' || !data.url) {
    throw new ImageUploadError('failed');
  }
  return data.url;
}

/**
 * Open the system photo library and upload the chosen photo. Resolves `null`
 * when the user backs out without picking anything.
 */
export async function pickAndUploadImage(
  token: string | null | undefined,
): Promise<string | null> {
  // No permission pre-flight on purpose: on iOS 14+ the PHPicker needs none,
  // and the versioned docs call this out explicitly.
  const result = await ImagePicker.launchImageLibraryAsync({
    mediaTypes: ['images'],
    allowsEditing: false,
    // Maximum quality — required alongside `allowsEditing: false` to keep an
    // animated GIF animated instead of flattening its first frame.
    quality: 1,
  }).catch(() => {
    throw new ImageUploadError('failed');
  });

  if (result.canceled || !result.assets?.[0]) return null;
  return uploadImageAsset(result.assets[0], token);
}

/**
 * Upload state for one "Upload image" button: launches the library, enforces
 * the server's size/type rules client-side, fills the field via `onUploaded`
 * on success, and otherwise exposes a stable error code for the failure strip.
 */
export function useImageUpload(onUploaded: (url: string) => void) {
  const { session } = useAuth();
  const token = session?.token ?? null;
  const [uploading, setUploading] = useState(false);
  const [errorCode, setErrorCode] = useState<UploadErrorCode | null>(null);

  const pick = useCallback(async () => {
    setErrorCode(null);
    setUploading(true);
    try {
      const url = await pickAndUploadImage(token);
      if (url) onUploaded(url);
    } catch (e) {
      setErrorCode(e instanceof ImageUploadError ? e.code : 'failed');
    } finally {
      setUploading(false);
    }
  }, [token, onUploaded]);

  const clearError = useCallback(() => setErrorCode(null), []);

  return { pick, uploading, errorCode, clearError };
}
